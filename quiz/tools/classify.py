def score_item(item):
    tags = " ".join(item.get("tags") or [])
    text = item.get("text") or ""
    best = None
    for board, topic, words in RULES:
        score = 0
        for w in words:
            if w in tags:
                score += 2
            if w in text:
                score += 1
        if score and (best is None or score > best[0]):
            best = (score, board, topic)
    return (best[1], best[2]) if best else ("其他", "综合")


def main():
    dry = "--dry" in sys.argv
    dist = Counter()
    unmatched = []
    total = 0
    for path in sorted(MANIFEST_DIR.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        for page in data["pages"]:
            for item in page["items"]:
                if item.get("kind") == "stem":
                    continue
                board, topic = score_item(item)
                item["board"] = board
                item["topic"] = topic
                dist[(board, topic)] += 1
                total += 1
                if topic == "综合":
                    unmatched.append(item["id"])
        if not dry:
            path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"{total} 道题" + ("（dry run，未写回）" if dry else "，已写回 manifest"))
    boards = Counter()
    for (b, t), n in dist.items():
        boards[b] += n
    for b, n in boards.most_common():
        print(f"\n{b}（{n}）")
        for (bb, t), m in sorted(dist.items(), key=lambda x: -x[1]):
            if bb == b:
                print(f"   {t:14s} {m}")
    if unmatched:
        print(f"\n未归类 {len(unmatched)} 条：{', '.join(unmatched[:20])}")


if __name__ == "__main__":
    main()
